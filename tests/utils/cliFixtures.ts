import { spawnSync, type SpawnSyncReturns } from "node:child_process";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { temporaryRoot, tsconfigJson, writeFiles } from "./fixtures.js";

const packageEntry = JSON.stringify(pathToFileURL(resolve("dist/index.js")).href);
const fixtureTsconfig = tsconfigJson({ module: "ESNext", moduleResolution: "Bundler", target: "ES2022" }, { include: ["src/**/*.ts"] });

const fixturePackage = JSON.stringify({ name: "fixture", private: true, type: "module" });

export const rootFixture = (body = "export const value = 1;"): string => {
  const root = temporaryRoot("architecture-cli-");
  writeFiles(root, {
    "src/abc.ts": body,
    "tsconfig.json": fixtureTsconfig,
    "package.json": fixturePackage,
    "architecture.config.ts": `import { defineArchitecture } from ${packageEntry};
    export default defineArchitecture({
      projects: { tsconfigs: ["tsconfig.json"] },
      naming: { case: "PascalCase" },
      layers: { app: { description: "App", files: ["src/abc.ts"], entry: { reason: "The fixture's only file.", exports: "all" } } },
    });`,
  });
  return root;
};

export const generatedFixture = (body: string): string => {
  const root = temporaryRoot("architecture-generated-");
  writeFiles(root, {
    "src/data.gen.ts": "export const value = 1;",
    "src/routes.gen.ts": body,
    "tsconfig.json": fixtureTsconfig,
    "package.json": fixturePackage,
    "architecture.config.ts": `import { defineArchitecture } from ${packageEntry};
    export default defineArchitecture({
      projects: { tsconfigs: ["tsconfig.json"] },
      layers: {
        data: { description: "Generated data", files: ["src/data.gen.ts"], generated: { reason: "Regenerated by the data tool." }, entry: { reason: "The data tool's consumers load it." } },
        routes: { description: "Generated routes", files: ["src/routes.gen.ts"], generated: { reason: "Regenerated by the router plugin." }, entry: { reason: "The router loads the route tree." } },
      },
    });`,
  });
  return root;
};

/** Runs the packaged CLI in cwd. */
export const run = (args: readonly string[], cwd: string): SpawnSyncReturns<string> => spawnSync(process.execPath, [resolve("dist/cli.js"), ...args], { cwd, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });

