import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";

import { defineArchitecture } from "../src/config/defineArchitecture.js";
import { compileOxlintConfig } from "../src/runner/compileOxlintConfig.js";
import { temporaryRoot, tsconfigJson, writeFiles } from "./utils/fixtures.js";

const packageEntry = JSON.stringify(pathToFileURL(resolve("dist/index.js")).href);
const fixtureTsconfig = tsconfigJson({ module: "ESNext", moduleResolution: "Bundler", target: "ES2022" }, { include: ["src/**/*.ts"] });

const rootFixture = (body = "export const value = 1;"): string => {
  const root = temporaryRoot("architecture-cli-");
  writeFiles(root, {
    "src/abc.ts": body,
    "tsconfig.json": fixtureTsconfig,
    "architecture.config.ts": `import { defineArchitecture } from ${packageEntry};
    export default defineArchitecture({
      projects: { tsconfigs: ["tsconfig.json"] },
      naming: { case: "PascalCase" },
      layers: { app: { description: "App", files: ["src/abc.ts"] } },
    });`,
  });
  return root;
};

const generatedFixture = (body: string): string => {
  const root = temporaryRoot("architecture-generated-");
  writeFiles(root, {
    "src/data.gen.ts": "export const value = 1;",
    "src/routes.gen.ts": body,
    "tsconfig.json": fixtureTsconfig,
    "architecture.config.ts": `import { defineArchitecture } from ${packageEntry};
    export default defineArchitecture({
      projects: { tsconfigs: ["tsconfig.json"] },
      layers: {
        data: { description: "Generated data", files: ["src/data.gen.ts"], generated: { reason: "Regenerated by the data tool." } },
        routes: { description: "Generated routes", files: ["src/routes.gen.ts"], generated: { reason: "Regenerated by the router plugin." } },
      },
    });`,
  });
  return root;
};

const run = (args: readonly string[], cwd: string) => spawnSync(process.execPath, [resolve("dist/cli.js"), ...args], { cwd, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });

const parseOutput = (stdout: string): unknown => JSON.parse(stdout);

const hasRunDirectory = (root: string): boolean => readdirSync(root).some((file) => file.startsWith(".architecture-run-"));

describe("packaged CLI", () => {
  it("describes the architecture from configuration alone", () => {
    const root = rootFixture();
    const result = run(["describe", "--json"], root);
    expect(result.status, result.stderr).toBe(0);
    expect(parseOutput(result.stdout)).toHaveProperty("layers.0.name", "app");
    expect(run(["describe"], root).stdout).toContain("Layers, in dependency order");
  });
  it("requires configuration rather than falling back to lint", () => {
    const root = temporaryRoot("architecture-empty-");
    const result = run([], root);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("Required architecture configuration not found");
  });
  it("explains a file relative to the explicit config root from another cwd", () => {
    const root = rootFixture();
    const result = run(["explain", "src/abc.ts", "--config", join(root, "architecture.config.ts")], dirname(root));
    expect(result.status, result.stderr).toBe(0);
    const explained = parseOutput(result.stdout);
    expect(explained).toHaveProperty("file", "src/abc.ts");
    expect(explained).toHaveProperty("matchingLayers.0.name", "app");
    expect(explained).toHaveProperty("policy.naming", { case: "PascalCase" });
  });
  it("fails classification of selected source before --fix can modify it", () => {
    const root = rootFixture();
    writeFiles(root, { "src/unclassified.ts": "export {};" });
    const result = run(["--fix"], root);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("file-classification");
    expect(hasRunDirectory(root)).toBe(false);
  });
  it("ignores unrelated files and supports an mts architecture definition", () => {
    const root = rootFixture();
    renameSync(join(root, "architecture.config.ts"), join(root, "architecture.config.mts"));
    writeFileSync(join(root, "unrelated.ts"), "invalid TypeScript that is outside include");
    writeFileSync(join(root, "README.md"), "No allowlist needed");
    const result = run(["explain", "src/abc.ts"], root);
    expect(result.status, result.stderr).toBe(0);
    expect(parseOutput(result.stdout)).toHaveProperty("issues", []);
  });
  it("rejects broad suppression before invoking lint", () => {
    const root = rootFixture("/* oxlint-disable */\nexport const value = 1;");
    const result = run([], root);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("reasoned-suppressions");
  });
  it("does not check suppressions in generated files", () => {
    const root = generatedFixture("/* eslint-disable */\n// @ts-nocheck\nexport const routes = [] as any;");
    const result = run(["explain", "src/routes.gen.ts"], root);
    expect(result.status, result.stderr).toBe(0);
    const explained = parseOutput(result.stdout);
    expect(explained).toHaveProperty("issues", []);
    expect(explained).toHaveProperty("policy.generated", { reason: "Regenerated by the router plugin." });
  });
  it("reports a configuration file as exempt from named exports", () => {
    const root = rootFixture();
    writeFileSync(join(root, "architecture.config.ts"), readFileSync(join(root, "architecture.config.ts"), "utf8").replace('files: ["src/abc.ts"]', 'files: ["src/abc.ts", "src/tool.config.ts"]'));
    writeFileSync(join(root, "src/tool.config.ts"), "export default {};");
    const result = run(["explain", "src/tool.config.ts"], root);
    expect(parseOutput(result.stdout)).toHaveProperty("namedExportsExempt", true);
  });
  it("never lints generated files but still checks their imports", () => {
    // Only generated files: the run never starts Oxlint, so this needs no native binaries.
    const clean = run([], generatedFixture("/* eslint-disable */\nexport const routes = [] as any;"));
    expect(clean.status, clean.stdout + clean.stderr).toBe(0);
    const importing = run([], generatedFixture("export { value } from './data.gen.js';"));
    expect(importing.status).toBe(1);
    expect(importing.stderr).toContain("allowed-imports");
    expect(importing.stderr).toContain("routes may not import data");
  });
  it("passes exact absolute selectors to native Oxlint, including glob metacharacters", () => {
    const root = temporaryRoot("architecture[glob]-");
    const path = join(root, "src", "[slug].ts");
    writeFiles(root, { "src/[slug].ts": "debugger;" });
    const architecture = defineArchitecture({ projects: { tsconfigs: ["tsconfig.json"] }, layers: { app: { description: "App", files: ["src/**"] } } });
    const policy = architecture.layers.app?.policy ?? expect.unreachable("the app layer is defined");
    const config = compileOxlintConfig([{ path, relative: "src/[slug].ts", layer: "app", policy }], []);
    // Isolate glob behavior from this VM's unavailable large JS-plugin allocator.
    mkdirSync(join(root, ".run"));
    const configPath = join(root, ".run", "oxlint.json");
    writeFileSync(configPath, JSON.stringify({ categories: { correctness: "off" }, plugins: ["eslint"], overrides: config.overrides?.map((entry) => ({ files: entry.files, rules: { "no-debugger": "error" } })) }));
    const binary = join(dirname(createRequire(import.meta.url).resolve("oxlint/package.json")), "bin/oxlint");
    const result = spawnSync(process.execPath, [binary, "--config", configPath, "--no-ignore", path], { cwd: root, encoding: "utf8" });
    expect(result.status, result.stderr).toBe(1);
    expect(result.stdout).toContain("no-debugger");
  });
  it.runIf(process.env.ARCHITECTURE_NATIVE_TESTS === "1")("reports Pascal naming through the actual Oxlint runner", () => {
    const root = rootFixture();
    const result = run([], root);
    expect(result.status).toBe(1);
    expect(result.stdout + result.stderr).toContain("PascalCase");
    expect(result.stdout + result.stderr).toContain("file-naming");
    expect(hasRunDirectory(root)).toBe(false);
  });
});
